# Reproducible benchmark: every method on every dataset, plus a scalability study
# on generated instances. Writes CSV files and docs/BENCHMARK.md.
#
#   julia --project=. scripts/benchmark.jl [--quick]
#
# --quick uses shorter time limits and fewer generated instances (for CI/smoke tests).

using FreightDispatchSimulator
using CSV, DataFrames, Dates

const ROOT = joinpath(@__DIR__, "..")
const DOCS = get(ENV, "BENCHMARK_OUTDIR", joinpath(ROOT, "docs"))

quick = "--quick" in ARGS
milp_limit = quick ? 10.0 : 60.0
sizes = quick ? [5, 10] : [5, 10, 15, 20, 30, 40]
seeds = quick ? (1:1) : (1:3)

# Warm-up so compilation time is not measured
let (f, v) = generate_instance(4, 2; seed = 99)
    compare_methods(f, v; milp_time_limit = 5)
end

fmt(x::Real; d = 1) = isnan(x) ? "–" : d == 0 ? string(round(Int, x)) : string(round(x; digits = d))
fmt_time(t) = t < 0.01 ? "$(round(1000t; digits = 1)) ms" : t < 10 ? "$(round(t; digits = 2)) s" : "$(round(Int, t)) s"

# ---------------------------------------------------------------------------
# 1. Included datasets
dataset_rows = DataFrame()
for name in readdir(joinpath(ROOT, "data"))
    inst = load_instance(joinpath(ROOT, "data", name))
    table, _ = compare_methods(inst; milp_time_limit = milp_limit)
    insertcols!(table, 1, :dataset => name, :n_freights => length(inst.freights), :n_vehicles => length(inst.vehicles))
    append!(dataset_rows, table)
    @info "dataset done" name
end
mkpath(DOCS)
CSV.write(joinpath(DOCS, "benchmark_datasets.csv"), dataset_rows)

# ---------------------------------------------------------------------------
# 2. Scalability on generated instances
scal_rows = DataFrame()
for n in sizes, seed in seeds
    m = max(2, n ÷ 4)
    f, v = generate_instance(n, m; seed = seed)
    table, _ = compare_methods(f, v; milp_time_limit = milp_limit)
    greedy = filter(r -> r.method in first.(FreightDispatchSimulator.GREEDY_STRATEGIES), table)
    best_greedy = greedy[argmin(greedy.objective), :]
    ls = only(filter(r -> r.method == "LocalSearch", table))
    milp = only(filter(r -> r.method == "MILP", table))
    push!(scal_rows, (
        n_freights = n, n_vehicles = m, seed = seed,
        best_greedy = best_greedy.method,
        greedy_objective = best_greedy.objective, ls_objective = ls.objective, milp_objective = milp.objective,
        greedy_gap_pct = best_greedy.gap_to_best_pct, ls_gap_pct = ls.gap_to_best_pct, milp_gap_pct = milp.gap_to_best_pct,
        greedy_time_s = best_greedy.solve_time_s, ls_time_s = ls.solve_time_s, milp_time_s = milp.solve_time_s,
        milp_proven_optimal = milp.proven_optimal,
    ))
    @info "generated instance done" n seed
end
CSV.write(joinpath(DOCS, "benchmark_scalability.csv"), scal_rows)

# ---------------------------------------------------------------------------
# 3. Markdown report
io = IOBuffer()
println(io, "# Benchmark results\n")
println(io, "Generated by `julia --project=. scripts/benchmark.jl` on $(Dates.format(now(), "yyyy-mm-dd")) ",
    "(Julia $(VERSION), $(Sys.cpu_info()[1].model), $(Sys.CPU_THREADS) threads). ",
    "MILP time limit $(Int(milp_limit)) s. All methods are scored by replaying their assignment in the same simulation; ",
    "objective = km + 100 × lateness hours (+ 10 000 per unserved freight).\n")

println(io, "## Included datasets\n")
println(io, "Gap is relative to the best objective found for that dataset. ✓ = MILP proved optimality within the time limit.\n")
println(io, "| Dataset | Size | Method | Objective | Gap | km | On time | Lateness (h) | Time |")
println(io, "|---|---|---|---:|---:|---:|---:|---:|---:|")
for r in eachrow(dataset_rows)
    opt = r.method == "MILP" ? (r.proven_optimal ? " ✓" : " (limit)") : ""
    println(io, "| $(r.dataset) | $(r.n_freights)F/$(r.n_vehicles)V | $(r.method)$(opt) | $(fmt(r.objective; d = 0)) | ",
        "$(fmt(r.gap_to_best_pct))% | $(fmt(r.distance_km; d = 0)) | $(r.on_time)/$(r.n_freights) | $(fmt(r.lateness_h)) | $(fmt_time(r.solve_time_s)) |")
end

println(io, "\n## Scalability (generated instances)\n")
println(io, "`generate_instance(n, max(2, n ÷ 4); seed)` for seeds $(first(seeds))–$(last(seeds)); mean over seeds. ",
    "Gap is relative to the best of the three methods on each instance.\n")
println(io, "| Freights | Vehicles | Best greedy gap | Local search gap | MILP gap | Greedy time | Local search time | MILP time | MILP proven optimal |")
println(io, "|---:|---:|---:|---:|---:|---:|---:|---:|---:|")
for g in groupby(scal_rows, :n_freights)
    mean(x) = sum(x) / length(x)
    println(io, "| $(g.n_freights[1]) | $(g.n_vehicles[1]) | $(fmt(mean(g.greedy_gap_pct)))% | $(fmt(mean(g.ls_gap_pct)))% | ",
        "$(fmt(mean(g.milp_gap_pct)))% | $(fmt_time(mean(g.greedy_time_s))) | $(fmt_time(mean(g.ls_time_s))) | ",
        "$(fmt_time(mean(g.milp_time_s))) | $(count(g.milp_proven_optimal))/$(nrow(g)) |")
end
write(joinpath(DOCS, "BENCHMARK.md"), take!(io))
println("Wrote BENCHMARK.md and CSV files to ", DOCS)

include(joinpath(@__DIR__, "scalability_chart.jl"))
scalability_svg(joinpath(DOCS, "benchmark_scalability.csv"), joinpath(DOCS, "assets", "scalability.svg"); time_limit = milp_limit)
